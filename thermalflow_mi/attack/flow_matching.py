"""Stage 1b: train the flow matching prior on the attacker's auxiliary data.

Conditional flow matching with the optimal transport path (Lipman et al., ICLR 2023) and minibatch OT coupling
(Tong et al., TMLR 2024; code adapted from https://github.com/atong01/conditional-flow-matching):
    x_t = t x_1 + (1 - t) x_0,  x_0 ~ N(0, I),  x_1 ~ auxiliary data,  t ~ U[0, 1]
    loss = || v_theta(x_t, t[, c]) - (x_1 - x_0) ||^2   (summed over pixels, averaged over the batch)
In every minibatch, (x_0, x_1) pairs are drawn from the exact OT plan between the noise and the images. For the
targeted attack the label c follows its image x_1 through the coupling.

Settings of the paper: 200 epochs, Adam lr 1e-4, batch 16, images 1 x 128 x 128 in [-1, 1].
"""
import json
import os
from pathlib import Path

import numpy as np
import ot
import torch
from torchdiffeq import odeint_adjoint as odeint
from torchvision.utils import save_image
from tqdm import tqdm

from ..metrics.fid import fid_from_arrays
from ..utils.images import to_unit


class _ODEFunc(torch.nn.Module):
    def __init__(self, model, labels=None):
        super().__init__()
        self.model, self.labels = model, labels

    def forward(self, t, x):
        with torch.no_grad():
            tt = t.repeat(x.shape[0])
            return self.model(x, tt) if self.labels is None else self.model(x, tt, self.labels)


class FlowMatchingTrainer:
    def __init__(self, model, device, out_dir, conditional, num_classes=None, lr=1e-4, image_size=128,
                 num_channels=1):
        self.model = model.to(device)
        self.device, self.conditional, self.num_classes = device, conditional, num_classes
        self.lr, self.d, self.c = lr, image_size, num_channels
        self.out = Path(out_dir)
        self.out.mkdir(parents=True, exist_ok=True)

    def _forward(self, x, t, labels):
        return self.model(x, t) if not self.conditional else self.model(x, t, labels)

    @torch.no_grad()
    def sample(self, n, labels=None):
        """Images generated by integrating dx/dt = v(x, t) from t = 0 to 1 (dopri5, tol 1e-5)."""
        was_training = self.model.training
        self.model.eval()
        if self.conditional and labels is None:
            labels = torch.arange(n, device=self.device) % self.num_classes
        if labels is not None:
            labels = torch.as_tensor(labels, device=self.device, dtype=torch.long).reshape(-1)
        z = torch.randn(n, self.c, self.d, self.d, device=self.device)
        x = odeint(_ODEFunc(self.model, labels), z, torch.tensor([0.0, 1.0], device=self.device),
                   atol=1e-5, rtol=1e-5, method="dopri5")[-1]
        if was_training:
            self.model.train()
        return x

    def _ot_pairs(self, x0, x1):
        a = np.ones(len(x0)) / len(x0)
        b = np.ones(len(x1)) / len(x1)
        M = ot.dist(x0.view(len(x0), -1).cpu().numpy(), x1.view(len(x1), -1).cpu().numpy())
        plan = ot.emd(a, b, M)
        p = plan.flatten()
        p = p / p.sum()
        choices = np.random.choice(plan.shape[0] * plan.shape[1], p=p, size=len(x0), replace=True)
        i, j = np.divmod(choices, plan.shape[1])
        return (torch.as_tensor(i, device=self.device, dtype=torch.long),
                torch.as_tensor(j, device=self.device, dtype=torch.long))

    def train(self, loader, epochs=200, checkpoint_every=100, fid_every=100, sample_every=1):
        """Train and save model_final.pt (plus model_<epoch>.pt every `checkpoint_every` epochs). Every
        `sample_every` epochs a 4 x 4 grid of samples is written; every `fid_every` epochs the FID between the
        prior's samples and its training images is logged (monitoring only)."""
        opt = torch.optim.Adam(self.model.parameters(), lr=self.lr)
        self.loader = loader
        tq = tqdm(range(epochs))
        for ep in tq:
            total, n_it, last = 0.0, 0, None
            for x, labels in loader:
                x = x.to(self.device, non_blocking=True)
                labels = labels.to(self.device, dtype=torch.long, non_blocking=True).reshape(-1)
                last = (x.detach(), labels.detach())
                z = torch.randn(x.shape[0], self.c, self.d, self.d, device=self.device)
                t = torch.rand(x.shape[0], 1, 1, 1, device=self.device)
                i, j = self._ot_pairs(z, x)
                x0, x1, c = z[i], x[j], labels[j]
                xt = t * x1 + (1.0 - t) * x0
                loss = torch.sum((self._forward(xt, t.reshape(-1), c) - (x1 - x0)) ** 2) / x.shape[0]
                opt.zero_grad(set_to_none=True)
                loss.backward()
                opt.step()
                total += loss.item()
                n_it += 1
                tq.set_description(f"epoch {ep + 1}/{epochs} loss={loss.item():.4f}")
            with open(self.out / "loss_epoch.txt", "a") as f:
                f.write(f"Epoch: {ep}, MeanLoss: {total / max(n_it, 1)}\n")
            if sample_every and ep % sample_every == 0 and last is not None:
                self._save_samples(*last, ep)
            if checkpoint_every and ep % checkpoint_every == 0:
                torch.save(self.model.state_dict(), self.out / f"model_{ep}.pt")
            if fid_every and ep % fid_every == 0:
                with open(self.out / "fid_training.txt", "a") as f:
                    f.write(f"Epoch: {ep}, FID: {self.training_fid()}\n")
        torch.save(self.model.state_dict(), self.out / "model_final.pt")
        (self.out / "training.json").write_text(json.dumps(
            {"epochs": epochs, "lr": self.lr, "batch_size": loader.batch_size, "conditional": self.conditional,
             "num_classes": self.num_classes, "num_images": len(loader.dataset)}, indent=2))
        return self.out / "model_final.pt"

    def _save_samples(self, x, labels, ep):
        n = min(16, x.shape[0]) if self.conditional else 16       # conditional: the labels of the last batch
        os.makedirs(self.out / "samples", exist_ok=True)
        lab = labels[:n] if self.conditional else None
        save_image(to_unit(self.sample(n, lab)), self.out / "samples" / f"samples_ep_{ep}.png", nrow=4)
        if ep == 0:
            save_image(to_unit(x[:n]), self.out / "samples" / "real_samples.png", nrow=4)

    def training_fid(self, num_samples=2048):
        """FID between the auxiliary images and as many prior samples (conditioned on the same labels)."""
        real, labs, got = [], [], 0
        n = min(num_samples, len(self.loader.dataset))
        for x, y in self.loader:
            real.append(x[:n - got])
            labs.append(y[:n - got].long())
            got += len(real[-1])
            if got >= n:
                break
        real, labs = torch.cat(real), torch.cat(labs)
        fake = torch.cat([self.sample(len(labs[s:s + 50]), labs[s:s + 50] if self.conditional else None).cpu()
                          for s in range(0, n, 50)])
        rgb = lambda t: to_unit(t).repeat(1, 3, 1, 1).cpu().numpy()   # noqa: E731
        return fid_from_arrays(rgb(real), rgb(fake), device=self.device, batch_size=min(50, n))
